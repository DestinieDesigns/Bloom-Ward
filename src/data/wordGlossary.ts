export function extractScriptureReference(text: string): { reference: string; book: string } | null {
  if (!text || typeof text !== 'string') return null;
  const trimmed = text.trim();

  // Check against Bible book names
  for (const book of SCRIPTURE_BOOK_NAMES) {
    const escaped = book.replace(/\s+/g, '\\s+');
    const regex = new RegExp(`(?:\\b|\\()(${escaped})\\s+(\\d+)(?::(\\d+(?:-\\d+)?))?(?:\\b|\\))`, 'i');
    const match = trimmed.match(regex);
    if (match) {
      const fullRef = match[3] ? `${book} ${match[2]}:${match[3]}` : `${book} ${match[2]}`;
      return { reference: fullRef, book };
    }
  }

  // General Chapter:Verse pattern (e.g. "Eph 1:5" or "Rom 8:28")
  const generalRegex = /\b([1-3]?\s*[A-Za-z]+)\s+(\d+):(\d+(?:-\d+)?)\b/;
  const genMatch = trimmed.match(generalRegex);
  if (genMatch) {
    return {
      reference: `${genMatch[1]} ${genMatch[2]}:${genMatch[3]}`,
      book: genMatch[1].trim()
    };
  }

  return null;
}

